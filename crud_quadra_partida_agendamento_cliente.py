def inserir_dados_de_exemplo():
    """Insere os exemplos uma unica vez, sem duplicar IDs ja cadastrados.

    Os IDs abaixo sao exemplos fixos para facilitar os relacionamentos.
    ON CONFLICT DO NOTHING ignora um ID que ja exista.
    """

    try:
        # Primeiro cadastra quadras, pois agendamento depende delas.
        cursor.executemany(
            """INSERT INTO quadra (id_quadra, preco, coberta)
               VALUES (%s, %s, %s)
               ON CONFLICT (id_quadra) DO NOTHING""",
            [
                (1, 100.00, True),
                (2, 100.00, True),
                (3, 90.00, False),
                (4, 90.00, False)
            ]
        )

        # Depois cadastra partidas, pois agendamento tambem depende delas.
        cursor.executemany(
            """INSERT INTO partida (id_partida, nome_artilheiro, total_gols)
               VALUES (%s, %s, %s)
               ON CONFLICT (id_partida) DO NOTHING""",
            [
                (1, "Carlos", 2),
                (2, "João", 3),
                (3, "Pedro", 1),
                (4, "Marcos", 4)
            ]
        )

        # Cliente nao esta ligado a agendamento no modelo atual.
        cursor.executemany(
            """INSERT INTO cliente (id_cliente, nome, telefone, email)
               VALUES (%s, %s, %s, %s)
               ON CONFLICT (id_cliente) DO NOTHING""",
            [
                (1, "Pedro Ricardo Souza", "51 93425644", "pedro.ricardo23@gmail.com"),
                (2, "Pedro Augusto Silva", "47 98675632", "pedro.aug3412@gmail.com"),
                (3, "Pedro Souza", "51 86655434", "pedro.souza2345@gmail.com"),
                (4, "Ricardo José", "53 97985891", "ricardo.santos45@gmail.com"),
                (5, "Fabricio Souza", None, None),
                (6, "Joao Santos", None, None),
                (7, "Joao Pedro Silva", None, None)
            ]
        )

        # Por ultimo insere agendamentos usando IDs de quadras e partidas acima.
        cursor.executemany(
            """INSERT INTO agendamento
               (id_agendamento, id_quadra, tempo_termino_max, hora, id_partida)
               VALUES (%s, %s, %s, %s, %s)
               ON CONFLICT (id_agendamento) DO NOTHING""",
            [
                (1, 1, 55, datetime(2026, 10, 21, 20, 0), 1),
                (2, 2, 51, datetime(2026, 10, 22, 20, 0), 2),
                (3, 3, 52, datetime(2026, 9, 13, 20, 0), 3),
                (4, 4, 59, datetime(2026, 9, 21, 20, 0), 4),
                (5, 1, 50, datetime(2026, 10, 19, 20, 0), 1),
                (6, 2, 59, datetime(2026, 8, 17, 20, 0), 2),
                (7, 3, 58, datetime(2026, 9, 15, 20, 0), 3),
                (8, 4, 59, datetime(2026, 10, 23, 20, 0), 4)
            ]
        )

        # Como inserimos IDs fixos, ajustamos as sequencias para o proximo ID
        # automatico ser maior que o maior ID ja cadastrado.
        for tabela, coluna in [
            ("quadra", "id_quadra"),
            ("partida", "id_partida"),
            ("cliente", "id_cliente"),
            ("agendamento", "id_agendamento")
        ]:
            cursor.execute(
                f"""SELECT setval(
                    pg_get_serial_sequence('{tabela}', '{coluna}'),
                    COALESCE((SELECT MAX({coluna}) FROM {tabela}), 1),
                    EXISTS (SELECT 1 FROM {tabela})
                )"""
            )

        conexao.commit()
        print("Dados de exemplo inseridos (IDs existentes foram ignorados).")

    except pg.DatabaseError as e:
        print("Erro ao inserir dados de exemplo:", e)
        conexao.rollback()


