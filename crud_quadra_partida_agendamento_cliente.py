import psycopg2 as pg
from datetime import datetime


# ============================================================
# 1. CONFIGURACAO DA CONEXAO COM O POSTGRESQL
# ============================================================

# Estas variaveis serao preenchidas pela funcao conectar().
conexao = None
cursor = None


def conectar():
    """Abre a conexao com o banco de dados PostgreSQL."""
    global conexao, cursor

    conexao = pg.connect(
        host="localhost",
        database="NOME_DO_SEU_BANCO",  # Troque pelo nome do seu banco.
        user="postgres",               # Usuario do PostgreSQL.
        password="SUA_SENHA",          # Troque pela sua senha.
        port="5432"
    )
    cursor = conexao.cursor()
    print("Conectado ao PostgreSQL com sucesso!")


# ============================================================
# 2. CRIACAO DAS TABELAS
# ============================================================


def criar_tabelas():
    """Cria as tabelas caso elas ainda nao existam."""

    # QUADRA: guarda o preco e informa se a quadra e coberta.
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS quadra (
            id_quadra INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            preco NUMERIC(10, 2) NOT NULL,
            coberta BOOLEAN NOT NULL
        )
    """)

    # PARTIDA: guarda o nome do artilheiro e a quantidade de gols.
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS partida (
            id_partida INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nome_artilheiro VARCHAR(100) NOT NULL,
            total_gols INTEGER NOT NULL
        )
    """)

    # CLIENTE: guarda os dados de contato do cliente.
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS cliente (
            id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nome VARCHAR(150) NOT NULL,
            telefone VARCHAR(30),
            email VARCHAR(150)
        )
    """)

    # AGENDAMENTO: relaciona uma quadra com uma partida.
    # As chaves estrangeiras impedem referencias a quadras/partidas inexistentes.
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS agendamento (
            id_agendamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            id_quadra INTEGER NOT NULL REFERENCES quadra(id_quadra),
            tempo_termino_max INTEGER NOT NULL,
            hora TIMESTAMP NOT NULL,
            id_partida INTEGER NOT NULL REFERENCES partida(id_partida)
        )
    """)

    conexao.commit()
    print("Tabelas verificadas/criadas com sucesso!")


