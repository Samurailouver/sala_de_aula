# 3. CLASSE QUADRA E SEU CRUD
# ============================================================


class Quadra:
    """Representa uma quadra esportiva."""

    def __init__(self, id_quadra: int, preco: float, coberta: bool):
        self.id_quadra = id_quadra
        self.preco = preco
        self.coberta = coberta

    def __str__(self):
        return (
            f"Quadra(id={self.id_quadra}, preco=R$ {self.preco:.2f}, "
            f"coberta={self.coberta})"
        )

    def __repr__(self):
        return str(self)


def criar_quadra(preco: float, coberta: bool) -> Quadra | None:
    """CREATE: insere uma quadra; o banco gera o ID automaticamente."""
    try:
        cursor.execute(
            """INSERT INTO quadra (preco, coberta)
               VALUES (%s, %s) RETURNING id_quadra""",
            (preco, coberta)
        )
        id_quadra = cursor.fetchone()[0]
        conexao.commit()
        return Quadra(id_quadra, preco, coberta)
    except pg.DatabaseError as e:
        print("Erro ao criar quadra:", e)
        conexao.rollback()
        return None


def listar_quadras() -> list[Quadra]:
    """READ: retorna todas as quadras cadastradas."""
    quadras = []
    try:
        cursor.execute(
            "SELECT id_quadra, preco, coberta FROM quadra ORDER BY id_quadra"
        )
        for linha in cursor.fetchall():
            quadras.append(Quadra(linha[0], linha[1], linha[2]))
    except pg.DatabaseError as e:
        print("Erro ao listar quadras:", e)
        conexao.rollback()
    return quadras


def buscar_quadra(id_quadra: int) -> Quadra | None:
    """READ: procura uma quadra pelo ID."""
    try:
        cursor.execute(
            "SELECT id_quadra, preco, coberta FROM quadra WHERE id_quadra = %s",
            (id_quadra,)
        )
        linha = cursor.fetchone()
        if linha:
            return Quadra(linha[0], linha[1], linha[2])
        return None
    except pg.DatabaseError as e:
        print("Erro ao buscar quadra:", e)
        conexao.rollback()
        return None


def atualizar_quadra(quadra: Quadra) -> bool:
    """UPDATE: altera preco e cobertura da quadra informada."""
    try:
        cursor.execute(
            """UPDATE quadra SET preco = %s, coberta = %s
               WHERE id_quadra = %s""",
            (quadra.preco, quadra.coberta, quadra.id_quadra)
        )
        alteradas = cursor.rowcount
        conexao.commit()
        return alteradas > 0
    except pg.DatabaseError as e:
        print("Erro ao atualizar quadra:", e)
        conexao.rollback()
        return False


def deletar_quadra(id_quadra: int) -> bool:
    """DELETE: exclui a quadra pelo ID.

    Se houver agendamentos ligados a ela, a chave estrangeira impede a exclusao.
    """
    try:
        cursor.execute("DELETE FROM quadra WHERE id_quadra = %s", (id_quadra,))
        apagadas = cursor.rowcount
        conexao.commit()
        return apagadas > 0
    except pg.DatabaseError as e:
        print("Erro ao deletar quadra (verifique se ha agendamentos ligados):", e)
        conexao.rollback()
        return False


