    for item in listar_quadras():
        print(item)

    print("\n========== PARTIDAS ==========")
    for item in listar_partidas():
        print(item)

    print("\n========== CLIENTES ==========")
    for item in listar_clientes():
        print(item)

    print("\n========== AGENDAMENTOS ==========")
    for item in listar_agendamentos():
        print(item)

    # Consulta que junta agendamento, quadra e partida.
    print("\n========== RELATORIO DE AGENDAMENTOS ==========")
    cursor.execute("""
        SELECT
            a.id_agendamento,
            q.id_quadra,
            q.preco,
            q.coberta,
            a.tempo_termino_max,
            a.hora,
            p.id_partida,
            p.nome_artilheiro,
            p.total_gols
        FROM agendamento AS a
        INNER JOIN quadra AS q ON q.id_quadra = a.id_quadra
        INNER JOIN partida AS p ON p.id_partida = a.id_partida
        ORDER BY a.id_agendamento
    """)

    for linha in cursor.fetchall():
        print(linha)


